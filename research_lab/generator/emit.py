"""The adapter (AD4.2): builds a Python MODULE SOURCE STRING from a skeleton, a filler and
its compiled facts. This is the seam requirements section 4 verifies: the engine imports
/app/strategy.py and demands exactly one concrete Strategy subclass in it, the worker
writes that file byte-for-byte from research_strategies.source_code, so the emitter's
output IS the only door a generated strategy has into the engine.

Only the 'band_cap' skeleton (AD3) is implemented; a request for any other skeleton id
raises, since none other is admissible yet (theory.py already refuses an unknown skeleton
id at load, so reaching here with one is a generator bug, not an operator error).
"""
from __future__ import annotations

import hashlib

# The reserved prefix marking the generated namespace (R-G16). Fixed here once: a
# hand-authored strategy must not use it (the store does not enforce that, R-G16's own
# residual). AC-50 proves the build uses this exact value.
GENERATED_NAME_PREFIX = "gen__"

# derived.generator_quantile_window_bars (docs/research_lab/parameter_provenance.md).
# AMENDED 2026-09-20 (lane SK, `3.2b`, DECISIONS `#396` ruling 1): this used to be
# QUANTILE_MIN_BARS, the floor an EXPANDING quantile needed before it was defined. Under
# Pardo's own counting (strategy.py's used_degrees_of_freedom docstring, PDF page 326, book
# page 293) an expanding window reads every prior bar, so an honest degrees-of-freedom
# declaration for it is the whole window and check 1 would fail every generated candidate;
# a smaller declaration would be a fabrication. The fix is a ROLLING window of this many
# bars instead (the window's own length, not merely its floor), so the declaration is
# honest and finite. One constant, one provenance entry, one name the emitted module reads
# (the ruling's own words): QUANTILE_MIN_BARS is retired, not kept alongside this one.
QUANTILE_WINDOW_BARS = 20


def derive_strategy_name(theory_id: str, skeleton_id: str, filler_id: str) -> str:
    """R-G16: a derived, reproducible name carrying the reserved prefix. ':' is replaced
    with '_' because research_strategies.name is a plain identifier-shaped string, not a
    place to carry a raw filler id's own punctuation."""
    return f"{GENERATED_NAME_PREFIX}{theory_id}__{skeleton_id}__{filler_id.replace(':', '_')}"


def expression_sha256(expression: str) -> str:
    """Content identity of the emitted expression string (AD6.2's ux_gencand_identity)."""
    return hashlib.sha256(expression.encode("utf-8")).hexdigest()


def _double_quoted_python_literal(text: str) -> str:
    """A double-quoted Python string literal for `text`, escaping only backslash and
    double-quote (the two characters that would otherwise break out of the literal), and
    newlines (an expression is one line by construction, but this stays safe regardless).
    generated.py's own regex reverses exactly this escaping when it re-derives the hash."""
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{escaped}"'


def _emit_filler_class_builder(filler_id: str) -> str:
    """The module-level code that rebuilds the SAME compiled indicator class the generator
    resolved at generation time (AD4.1 step 1-2), read off FILLER_ID at import time. Both
    branches are always present in the emitted source (never only the one this filler
    needs), so AC-14's grep ("use_pd_eval is False wherever an expression is compiled")
    finds the from_expr call site in every generated module, whatever its own filler is."""
    return (
        "def _compiled_filler_class():\n"
        '    """Rebuild the compiled indicator class this module was generated from '
        "(AD4.1 step 1-2). use_pd_eval is passed explicitly wherever an expression is\n"
        '    compiled (R-G15, AC-14); a wqa101 filler needs no expression compile at all."""\n'
        '    if FILLER_ID.startswith("wqa101:"):\n'
        '        _, _, n = FILLER_ID.partition(":")\n'
        "        return vbt.IF.from_wqa101(int(n))\n"
        "    return vbt.IF.from_expr(EXPRESSION, use_pd_eval=False)\n"
    )


